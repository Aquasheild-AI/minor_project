"""
AquaShield Notification Dispatch Service.
Handles email notifications for critical alerts, outbreak warnings,
and high-priority water contamination advisories.
"""
import logging
from django.conf import settings
from django.contrib.auth import get_user_model
from django.core.mail import send_mail

logger = logging.getLogger(__name__)


def dispatch_alert_email(alert):
    """
    Sends an immediate email notification to Admin / Authority users whenever
    a new alert is broadcasted (manually by Health Authority or generated by ML predictive models).
    """
    try:
        User = get_user_model()

        # 1. Gather all active Authority / Admin email addresses
        admin_users = User.objects.filter(
            role='AUTHORITY',
            is_active=True,
            email__isnull=False,
        ).exclude(email='')

        recipients = set()
        for u in admin_users:
            if u.email and u.email.strip():
                recipients.add(u.email.strip())

        # 2. Include EMAIL_HOST_USER or DEFAULT_FROM_EMAIL if configured as fallback administrator inbox
        default_admin_email = getattr(settings, 'ADMIN_ALERT_EMAIL', None)
        if default_admin_email and '@' in default_admin_email:
            recipients.add(default_admin_email.strip())
        elif getattr(settings, 'EMAIL_HOST_USER', None) and '@' in settings.EMAIL_HOST_USER:
            recipients.add(settings.EMAIL_HOST_USER.strip())

        if not recipients:
            logger.info("No authority email recipients found for alert #%s dispatch.", getattr(alert, 'id', 'new'))
            return

        recipient_list = sorted(list(recipients))

        # 3. Format subject and detailed plain text body
        village_name = alert.village.name if alert.village else 'Unknown Village'
        district = getattr(alert.village, 'district', 'N/A') if alert.village else 'N/A'
        severity_label = alert.get_severity_display() if hasattr(alert, 'get_severity_display') else alert.severity
        alert_type_label = alert.get_alert_type_display() if hasattr(alert, 'get_alert_type_display') else alert.alert_type

        subject = f"[AquaShield {severity_label}] {alert.title} - {village_name}"

        body_lines = [
            "AquaShield Health Alert Dispatch",
            "==================================================",
            f"Alert ID:       #{alert.id}",
            f"Severity:       {severity_label}",
            f"Alert Type:     {alert_type_label}",
            f"Village:        {village_name} (District: {district})",
            f"Target:         {alert.get_target_audience_display() if hasattr(alert, 'get_target_audience_display') else alert.target_audience}",
            f"Generated By:   {'AI Predictive Risk Engine' if alert.generated_by_ai else 'Health Authority Manual Broadcast'}",
            f"Created At:     {alert.created_at.strftime('%Y-%m-%d %H:%M:%S UTC') if alert.created_at else 'Just now'}",
            "--------------------------------------------------",
            "Message:",
            f"{alert.message}",
            "",
        ]

        if alert.action_required:
            body_lines.extend([
                "Recommended Action Required:",
                f"{alert.action_required}",
                "",
            ])

        body_lines.extend([
            "--------------------------------------------------",
            "Please log in to the AquaShield Authority Dashboard to review and manage active advisories.",
            "AquaShield-AI Early Warning System",
        ])

        body = "\n".join(body_lines)
        from_email = getattr(settings, 'DEFAULT_FROM_EMAIL', None) or getattr(settings, 'EMAIL_HOST_USER', 'noreply@aquashield.ai')

        send_mail(
            subject=subject,
            message=body,
            from_email=from_email,
            recipient_list=recipient_list,
            fail_silently=True,
        )
        logger.info(
            "Dispatched alert #%s email notification to %d recipients (%s).",
            alert.id,
            len(recipient_list),
            ", ".join(recipient_list),
        )
    except Exception as e:
        logger.warning("Failed to dispatch alert email notification for alert #%s: %s", getattr(alert, 'id', 'unknown'), e)
