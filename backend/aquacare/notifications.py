"""
AquaShield Notification Dispatch Service.
Handles email notifications for critical alerts, outbreak warnings,
and high-priority water contamination advisories and emergency deployments.
"""
import logging
from django.conf import settings
from django.contrib.auth import get_user_model
from .email_service import send_transactional_email

logger = logging.getLogger(__name__)


def dispatch_alert_email(alert):
    """
    Sends an immediate email notification to Admin / Authority users and local Health Workers
    whenever a new alert is broadcasted (manually by Health Authority or generated by ML predictive models).
    """
    try:
        User = get_user_model()

        recipients = set()

        # 1. Active Authority / Admin email addresses
        admin_users = User.objects.filter(
            role='AUTHORITY',
            is_active=True,
            email__isnull=False,
        ).exclude(email='')

        for u in admin_users:
            if u.email and '@' in u.email:
                recipients.add(u.email.strip())

        # 2. Assigned Health Workers for the affected village
        if getattr(alert, 'village', None):
            assigned_workers = User.objects.filter(
                role='HEALTH_WORKER',
                assigned_villages=alert.village,
                is_active=True,
                email__isnull=False,
            ).exclude(email='')
            for w in assigned_workers:
                if w.email and '@' in w.email:
                    recipients.add(w.email.strip())

        # 3. Always include primary administrator/host inbox from settings
        default_admin = getattr(settings, 'ADMIN_ALERT_EMAIL', None) or getattr(settings, 'EMAIL_HOST_USER', None)
        if default_admin and '@' in default_admin:
            recipients.add(default_admin.strip())

        if not recipients:
            logger.info("No email recipients found for alert #%s dispatch.", getattr(alert, 'id', 'new'))
            return

        recipient_list = sorted(list(recipients))

        village_name = alert.village.name if alert.village else 'All Covered Regions'
        district = getattr(alert.village, 'district', 'Varanasi Division') if alert.village else 'Varanasi Division'
        severity_label = alert.get_severity_display() if hasattr(alert, 'get_severity_display') else alert.severity
        alert_type_label = alert.get_alert_type_display() if hasattr(alert, 'get_alert_type_display') else alert.alert_type
        target_audience_label = alert.get_target_audience_display() if hasattr(alert, 'get_target_audience_display') else alert.target_audience
        created_time = alert.created_at.strftime('%Y-%m-%d %H:%M:%S UTC') if getattr(alert, 'created_at', None) else 'Just now'
        generated_by = 'AI Predictive Risk Engine' if getattr(alert, 'generated_by_ai', False) else 'Health Authority Direct Broadcast'

        subject = f"[AquaShield {severity_label}] {alert.title} - {village_name}"

        # Plain text representation
        body_lines = [
            "==================================================",
            f"AQUASHIELD HEALTH ALERT: {severity_label.upper()}",
            "==================================================",
            f"Alert Title:     {alert.title}",
            f"Alert ID:        #{getattr(alert, 'id', 'NEW')}",
            f"Severity:        {severity_label}",
            f"Alert Category:  {alert_type_label}",
            f"Target Village:  {village_name} (District: {district})",
            f"Audience:        {target_audience_label}",
            f"Broadcast Origin:{generated_by}",
            f"Timestamp:       {created_time}",
            "--------------------------------------------------",
            "Advisory Details:",
            f"{alert.message}",
            "",
        ]

        if alert.action_required:
            body_lines.extend([
                "Required Field Action:",
                f"{alert.action_required}",
                "",
            ])

        body_lines.extend([
            "--------------------------------------------------",
            "Please log in to the AquaShield Health Portal to coordinate response measures.",
            "AquaShield Epidemic Intelligence & Water Safety Platform",
        ])
        text_body = "\n".join(body_lines)

        # HTML representation
        badge_color = "#dc2626" if severity_label.upper() in ('CRITICAL', 'HIGH') else "#d97706"
        html_body = f"""
        <!DOCTYPE html>
        <html>
        <head>
          <meta charset="utf-8">
          <style>
            body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; background-color: #f8fafc; margin: 0; padding: 24px; color: #1e293b; }}
            .container {{ max-width: 600px; margin: 0 auto; background: #ffffff; border-radius: 12px; border: 1px solid #e2e8f0; overflow: hidden; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1); }}
            .header {{ background: #0f172a; padding: 24px; color: #ffffff; }}
            .badge {{ display: inline-block; padding: 4px 12px; border-radius: 9999px; font-size: 12px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.05em; background: {badge_color}; color: #ffffff; margin-bottom: 8px; }}
            .title {{ font-size: 20px; font-weight: 800; margin: 0; line-height: 1.3; }}
            .content {{ padding: 24px; }}
            .meta-grid {{ display: table; width: 100%; border-collapse: collapse; margin-bottom: 20px; }}
            .meta-row {{ display: table-row; }}
            .meta-cell {{ display: table-cell; padding: 8px 12px; border-bottom: 1px solid #f1f5f9; font-size: 13px; }}
            .meta-label {{ color: #64748b; font-weight: 600; width: 35%; }}
            .meta-val {{ color: #0f172a; font-weight: 700; }}
            .message-box {{ background: #f8fafc; border-left: 4px solid {badge_color}; padding: 16px; border-radius: 0 8px 8px 0; margin-bottom: 20px; font-size: 14px; line-height: 1.6; color: #334155; }}
            .action-box {{ background: #fef2f2; border: 1px solid #fecaca; padding: 16px; border-radius: 8px; margin-bottom: 20px; font-size: 14px; line-height: 1.5; color: #991b1b; }}
            .footer {{ background: #f8fafc; padding: 16px 24px; text-align: center; font-size: 12px; color: #94a3b8; border-top: 1px solid #e2e8f0; }}
          </style>
        </head>
        <body>
          <div class="container">
            <div class="header">
              <span class="badge">{severity_label} Alert</span>
              <h1 class="title">{alert.title}</h1>
              <div style="font-size: 13px; color: #94a3b8; margin-top: 6px;">Target Village: <strong>{village_name}</strong> | District: <strong>{district}</strong></div>
            </div>
            <div class="content">
              <div class="meta-grid">
                <div class="meta-row"><div class="meta-cell meta-label">Alert Type:</div><div class="meta-cell meta-val">{alert_type_label}</div></div>
                <div class="meta-row"><div class="meta-cell meta-label">Target Audience:</div><div class="meta-cell meta-val">{target_audience_label}</div></div>
                <div class="meta-row"><div class="meta-cell meta-label">Dispatched By:</div><div class="meta-cell meta-val">{generated_by}</div></div>
                <div class="meta-row"><div class="meta-cell meta-label">Broadcast Time:</div><div class="meta-cell meta-val">{created_time}</div></div>
              </div>
              <div class="message-box">
                <div style="font-weight: 700; margin-bottom: 6px; color: #0f172a;">Official Advisory Directive:</div>
                {alert.message}
              </div>
              {f'''<div class="action-box">
                <div style="font-weight: 700; margin-bottom: 4px;">Recommended Community Action:</div>
                {alert.action_required}
              </div>''' if alert.action_required else ''}
            </div>
            <div class="footer">
              AquaShield Rural Epidemiological & Potable Water Security System<br>
              Automated Emergency Broadcast Service
            </div>
          </div>
        </body>
        </html>
        """

        send_transactional_email(
            to=recipient_list,
            subject=subject,
            html_content=html_body,
            text_content=text_body,
            fail_silently=True,
        )
        logger.info(
            "Dispatched alert #%s notification email to %d recipients (%s).",
            getattr(alert, 'id', 'new'),
            len(recipient_list),
            ", ".join(recipient_list),
        )
    except Exception as e:
        logger.warning("Failed to dispatch alert email notification for alert #%s: %s", getattr(alert, 'id', 'unknown'), e)


def dispatch_emergency_email(dispatch, triggered_by=None):
    """
    Sends an immediate deployment email notification to Health Authorities,
    Assigned Health Workers, and Medical Teams whenever an Ambulance or Rapid Response Unit is dispatched.
    """
    try:
        User = get_user_model()
        recipients = set()

        # 1. Authority / Admin users
        admin_users = User.objects.filter(
            role='AUTHORITY',
            is_active=True,
            email__isnull=False,
        ).exclude(email='')
        for u in admin_users:
            if u.email and '@' in u.email:
                recipients.add(u.email.strip())

        # 2. Health Workers assigned to target village
        if getattr(dispatch, 'village', None):
            assigned_workers = User.objects.filter(
                role='HEALTH_WORKER',
                assigned_villages=dispatch.village,
                is_active=True,
                email__isnull=False,
            ).exclude(email='')
            for w in assigned_workers:
                if w.email and '@' in w.email:
                    recipients.add(w.email.strip())

        # 3. Triggering User email
        if triggered_by and getattr(triggered_by, 'email', None) and '@' in triggered_by.email:
            recipients.add(triggered_by.email.strip())

        # 4. Primary system inbox from settings
        default_admin = getattr(settings, 'ADMIN_ALERT_EMAIL', None) or getattr(settings, 'EMAIL_HOST_USER', None)
        if default_admin and '@' in default_admin:
            recipients.add(default_admin.strip())

        if not recipients:
            logger.info("No recipients found for emergency dispatch #%s.", getattr(dispatch, 'id', 'new'))
            return

        recipient_list = sorted(list(recipients))

        village_name = dispatch.village.name if dispatch.village else 'Target Village'
        district = getattr(dispatch.village, 'district', 'Varanasi Division') if dispatch.village else 'Varanasi Division'
        dispatch_type_label = dispatch.get_dispatch_type_display() if hasattr(dispatch, 'get_dispatch_type_display') else dispatch.dispatch_type
        priority_label = dispatch.get_priority_display() if hasattr(dispatch, 'get_priority_display') else dispatch.priority
        created_time = dispatch.created_at.strftime('%Y-%m-%d %H:%M:%S UTC') if getattr(dispatch, 'created_at', None) else 'Just now'
        dispatched_by_name = (
            triggered_by.get_full_name() or triggered_by.username
            if triggered_by
            else (dispatch.dispatched_by.get_full_name() if getattr(dispatch, 'dispatched_by', None) else 'Health Authority')
        )

        subject = f"[EMERGENCY DISPATCH - {priority_label.upper()}] {dispatch_type_label} -> {village_name}"

        # Plain text body
        text_body = (
            f"CRITICAL HEALTH RESPONSE MOBILIZATION\n"
            f"==================================================\n"
            f"Target Village:     {village_name} (District: {district})\n"
            f"Dispatch Unit:      {dispatch_type_label}\n"
            f"Priority Level:     {priority_label}\n"
            f"Vehicle / Unit ID:  {dispatch.vehicle_number or 'Ambulance Support Unit'}\n"
            f"Team Lead:          {dispatch.team_lead_name} (Phone: {dispatch.team_lead_phone or 'N/A'})\n"
            f"Estimated Arrival:  {dispatch.estimated_arrival_minutes} minutes\n"
            f"Authorized By:      {dispatched_by_name}\n"
            f"Dispatched At:      {created_time}\n"
            f"--------------------------------------------------\n"
            f"Deployment Directives & Reason:\n{dispatch.reason}\n\n"
            f"Notes: {dispatch.notes or 'None'}\n\n"
            f"All field teams and clinic staff in {village_name} must prepare patient reception and triage immediately.\n"
            f"AquaShield Rapid Emergency Deployment Protocol"
        )

        # HTML body
        html_body = f"""
        <!DOCTYPE html>
        <html>
        <head>
          <meta charset="utf-8">
          <style>
            body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; background-color: #f8fafc; margin: 0; padding: 24px; color: #1e293b; }}
            .container {{ max-width: 600px; margin: 0 auto; background: #ffffff; border-radius: 12px; border: 1px solid #e2e8f0; overflow: hidden; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1); }}
            .header {{ background: #dc2626; padding: 24px; color: #ffffff; }}
            .badge {{ display: inline-block; padding: 4px 12px; border-radius: 9999px; font-size: 12px; font-weight: 800; text-transform: uppercase; letter-spacing: 0.05em; background: #ffffff; color: #dc2626; margin-bottom: 8px; }}
            .title {{ font-size: 22px; font-weight: 800; margin: 0; line-height: 1.3; color: #ffffff; }}
            .content {{ padding: 24px; }}
            .meta-grid {{ display: table; width: 100%; border-collapse: collapse; margin-bottom: 20px; }}
            .meta-row {{ display: table-row; }}
            .meta-cell {{ display: table-cell; padding: 8px 12px; border-bottom: 1px solid #f1f5f9; font-size: 13px; }}
            .meta-label {{ color: #64748b; font-weight: 600; width: 35%; }}
            .meta-val {{ color: #0f172a; font-weight: 700; }}
            .directive-box {{ background: #fef2f2; border-left: 4px solid #dc2626; padding: 16px; border-radius: 0 8px 8px 0; margin-bottom: 20px; font-size: 14px; line-height: 1.6; color: #991b1b; }}
            .eta-badge {{ font-size: 18px; font-weight: 800; color: #dc2626; }}
            .footer {{ background: #f8fafc; padding: 16px 24px; text-align: center; font-size: 12px; color: #94a3b8; border-top: 1px solid #e2e8f0; }}
          </style>
        </head>
        <body>
          <div class="container">
            <div class="header">
              <span class="badge">EMERGENCY DEPLOYMENT • {priority_label}</span>
              <h1 class="title">🚨 {dispatch_type_label} Mobilized</h1>
              <div style="font-size: 13px; color: #fecaca; margin-top: 6px;">Destination: <strong>{village_name}</strong> ({district})</div>
            </div>
            <div class="content">
              <div class="meta-grid">
                <div class="meta-row"><div class="meta-cell meta-label">Estimated ETA:</div><div class="meta-cell meta-val"><span class="eta-badge">{dispatch.estimated_arrival_minutes} Minutes</span></div></div>
                <div class="meta-row"><div class="meta-cell meta-label">Vehicle / Unit:</div><div class="meta-cell meta-val">{dispatch.vehicle_number or 'Ambulance Response Unit'}</div></div>
                <div class="meta-row"><div class="meta-cell meta-label">Team Lead:</div><div class="meta-cell meta-val">{dispatch.team_lead_name} (📞 {dispatch.team_lead_phone or 'N/A'})</div></div>
                <div class="meta-row"><div class="meta-cell meta-label">Dispatched By:</div><div class="meta-cell meta-val">{dispatched_by_name}</div></div>
                <div class="meta-row"><div class="meta-cell meta-label">Dispatch Time:</div><div class="meta-cell meta-val">{created_time}</div></div>
              </div>
              <div class="directive-box">
                <div style="font-weight: 800; margin-bottom: 6px;">Deployment Directives & Reason:</div>
                {dispatch.reason}
              </div>
              {f'''<div style="font-size: 13px; color: #64748b; margin-top: 8px;"><strong>Field Notes:</strong> {dispatch.notes}</div>''' if dispatch.notes else ''}
            </div>
            <div class="footer">
              AquaShield Emergency Dispatch Command • Field Response Unit<br>
              Please prepare field triage and coordinate with incoming medical staff immediately.
            </div>
          </div>
        </body>
        </html>
        """

        send_transactional_email(
            to=recipient_list,
            subject=subject,
            html_content=html_body,
            text_content=text_body,
            fail_silently=True,
        )
        logger.info(
            "Dispatched emergency dispatch #%s email notification to %d recipients (%s).",
            getattr(dispatch, 'id', 'new'),
            len(recipient_list),
            ", ".join(recipient_list),
        )
    except Exception as e:
        logger.warning("Failed to dispatch emergency deployment notification email for dispatch #%s: %s", getattr(dispatch, 'id', 'unknown'), e)
